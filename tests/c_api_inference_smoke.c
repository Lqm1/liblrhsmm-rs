static void close_scores_f64(LiblrhsmmRsHsmmScoresF64 **scores) { assert(liblrhsmm_rs_hsmm_scores_release_f64(scores) == 0); assert(*scores == NULL); }
static void read_scores_f64(LiblrhsmmRsHsmmScoresF64 *scores, double values[2][48]) {
    LiblrhsmmRsStateScoresF64 *begin = NULL, *end = NULL;
    assert(liblrhsmm_rs_hsmm_scores_get_begin_f64(scores, &begin) == 0);
    assert(liblrhsmm_rs_hsmm_scores_get_end_f64(scores, &end) == 0);
    close_scores_f64(&scores);
    assert(liblrhsmm_rs_state_scores_copy_values_f64(begin, 0, values[0], 48) == 0);
    assert(liblrhsmm_rs_state_scores_copy_values_f64(end, 0, values[1], 48) == 0);
    LiblrhsmmRsHsmmScoresF64 *imported = NULL, *clone = NULL;
    assert(liblrhsmm_rs_hsmm_scores_create_f64(begin, end, &imported) == 0);
    assert(liblrhsmm_rs_hsmm_scores_clone_f64(imported, &clone) == 0);
    close_scores_f64(&imported);
    close_scores_f64(&clone);
    assert(liblrhsmm_rs_state_scores_release_f64(&begin) == 0);
    assert(liblrhsmm_rs_state_scores_release_f64(&end) == 0);
}
static void check_f64(double actual, double expected) {
    assert(fabs(actual-expected)/fmax(1.0,fabs(expected)) <= 2e-14);
}
static void exercise_f64(void) {
    size_t comparisons = 0;
    for (size_t fractional = 0; fractional < 2; ++fractional) {
    for (size_t scenario = 0; scenario < 4; ++scenario) {
        LiblrhsmmRsDurationF64 *durations[4] = {0};
        const LiblrhsmmRsDurationF64 *borrowed[4];
        for (size_t state = 0; state < 4; ++state) {
            LiblrhsmmRsDurationParametersF64 parameters = {0};
            assert(liblrhsmm_rs_duration_default_f64(&parameters) == 0);
            parameters.mean = 2.5 + state * 0.25; parameters.variance = 0.75 + state * 0.25;
            parameters.minimum = state == 1 ? 2 : -1; parameters.maximum = scenario == 3 && state == 1 ? 3 : 7;
            assert(liblrhsmm_rs_duration_create_f64(&parameters, &durations[state]) == 0); borrowed[state] = durations[state];
        }
        LiblrhsmmRsModelF64 *model = NULL;
        assert(liblrhsmm_rs_model_create_f64(NULL, 0, borrowed, 4, &model) == 0);
        for (size_t state = 0; state < 4; ++state) assert(liblrhsmm_rs_duration_release_f64(&durations[state]) == 0);
        int32_t boundaries[4] = {3,6,9,12}, labels[4] = {0,1,2,3};
        LiblrhsmmRsJumpF64 jumps[4][2] = {{{1,1}},{{1,1}},{{1,1}},{{1,1}}};
        LiblrhsmmRsJumpSliceF64 slices[4];
        if (scenario) {
            jumps[0][0] = (LiblrhsmmRsJumpF64){2, 0.2}; jumps[1][0] = (LiblrhsmmRsJumpF64){0, 0.15}; jumps[2][0] = (LiblrhsmmRsJumpF64){-1, 0.1};
            for (size_t state = 0; state < 3; ++state) jumps[state][1] = (LiblrhsmmRsJumpF64){1, 0.8};
        }
        for (size_t state = 0; state < 4; ++state) slices[state] = (LiblrhsmmRsJumpSliceF64){jumps[state], scenario && state < 3 ? 2 : 1};
        LiblrhsmmRsSegmentationF64 *seg = NULL; LiblrhsmmRsTransitionGraphF64 *graph = NULL;
        assert(liblrhsmm_rs_segmentation_create_f64(0, 4, boundaries, labels, NULL, slices, &seg) == 0);
        assert(liblrhsmm_rs_segmentation_build_transitions_f64(seg, &graph) == 0);
        double emissions[48]; const size_t desired[12] = {0,0,2,2,1,1,1,1,2,3,3,3};
        for (size_t frame = 0; frame < 12; ++frame) for (size_t state = 0; state < 4; ++state) {
            double residual = (double)frame - (double)state * 3.0;
            emissions[frame*4+state] = scenario == 3 ? (state == desired[frame] ? 0 : -50) : -residual*residual*0.125;
        }
        LiblrhsmmRsLogEmissionsF64 *log = NULL;
        assert(liblrhsmm_rs_log_emissions_create_f64(12,4,emissions,48,&log) == 0);
        LiblrhsmmRsHsmmSettingsF64 options;
        assert(liblrhsmm_rs_hsmm_settings_default_f64(&options) == 0);
        assert(options.temperature == 1 && options.duration_weight == 1 && options.state_radius == 5 && options.duration_extra == 30 && options.duration_extra_factor == 1);
        options.temperature = scenario == 2 ? 0.5 : 1; options.duration_weight = 0.75; options.state_radius = scenario == 2 ? 1 : 5; options.duration_extra = 3; options.duration_extra_factor = 0.5;
        if (fractional) { const double radii[4] = {0.25,0.5,1.75,2.5}; options.state_radius = radii[scenario]; }
        LiblrhsmmRsDurationPreparationF64 preparation = {2, options.duration_weight, options.temperature};
        LiblrhsmmRsPreparedModelF64 *prepared = NULL;
        assert(liblrhsmm_rs_model_prepare_f64(model,&preparation,&prepared) == 0);
        LiblrhsmmRsHsmmScoresF64 *scores = NULL;
        double forward[2][48], backward[2][48], values[2][48];
        assert(liblrhsmm_rs_model_forward_hsmm_f64(model,seg,log,&options,&scores) == 0); read_scores_f64(scores, forward);
        assert(liblrhsmm_rs_model_backward_hsmm_f64(model,seg,log,&options,&scores) == 0); read_scores_f64(scores, backward);
        for (size_t index = 0; index < 48; ++index) for (size_t field = 0; field < 4; ++field) {
            check_f64(field < 2 ? forward[field][index] : backward[field-2][index], reference_f64[fractional][scenario][index][field]); ++comparisons;
        }
        assert(liblrhsmm_rs_model_forward_hsmm_with_graph_f64(model,graph,log,&options,&scores) == 0); read_scores_f64(scores, values); assert(memcmp(values,forward,sizeof(values)) == 0);
assert(liblrhsmm_rs_model_backward_hsmm_with_graph_f64(model,graph,log,&options,&scores) == 0); read_scores_f64(scores, values); assert(memcmp(values,backward,sizeof(values)) == 0);
assert(liblrhsmm_rs_prepared_model_forward_hsmm_f64(prepared,seg,log,&options,&scores) == 0); read_scores_f64(scores, values); assert(memcmp(values,forward,sizeof(values)) == 0);
assert(liblrhsmm_rs_prepared_model_backward_hsmm_f64(prepared,seg,log,&options,&scores) == 0); read_scores_f64(scores, values); assert(memcmp(values,backward,sizeof(values)) == 0);
assert(liblrhsmm_rs_prepared_model_forward_hsmm_with_graph_f64(prepared,graph,log,&options,&scores) == 0); read_scores_f64(scores, values); assert(memcmp(values,forward,sizeof(values)) == 0);
assert(liblrhsmm_rs_prepared_model_backward_hsmm_with_graph_f64(prepared,graph,log,&options,&scores) == 0); read_scores_f64(scores, values); assert(memcmp(values,backward,sizeof(values)) == 0);
        LiblrhsmmRsHsmmPathF64 *path = NULL, *retained = NULL;
        assert(liblrhsmm_rs_model_viterbi_hsmm_f64(model,seg,log,&options,&path) == 0);
assert(liblrhsmm_rs_hsmm_path_release_f64(&path) == 0);
assert(liblrhsmm_rs_model_viterbi_hsmm_with_graph_f64(model,graph,log,&options,&path) == 0);
assert(liblrhsmm_rs_hsmm_path_release_f64(&path) == 0);
assert(liblrhsmm_rs_prepared_model_viterbi_hsmm_f64(prepared,seg,log,&options,&path) == 0);
assert(liblrhsmm_rs_hsmm_path_release_f64(&path) == 0);
assert(liblrhsmm_rs_prepared_model_viterbi_hsmm_with_graph_f64(prepared,graph,log,&options,&path) == 0);
        assert(liblrhsmm_rs_hsmm_path_clone_f64(path, &retained) == 0);
        assert(liblrhsmm_rs_hsmm_path_release_f64(&path) == 0);
        assert(liblrhsmm_rs_prepared_model_release_f64(&prepared) == 0);
        LiblrhsmmRsPathLayout layout;
        assert(liblrhsmm_rs_hsmm_path_layout_f64(retained,&layout) == 0);
        assert(layout.frames == 12 && layout.states == 4 && layout.occurrences == path_count_f64[fractional][scenario]);
        LiblrhsmmRsStateOccurrence occurrences[12];
        assert(liblrhsmm_rs_hsmm_path_copy_occurrences_f64(retained,0,occurrences,layout.occurrences) == 0);
        for (size_t index=0; index<layout.occurrences; ++index) { assert(occurrences[index].state == path_reference_f64[fractional][scenario][index].state); assert(occurrences[index].end == path_reference_f64[fractional][scenario][index].end); }
        assert(liblrhsmm_rs_hsmm_path_copy_occurrences_f64(retained,layout.occurrences,NULL,0) == 0);
        double likelihood;
        assert(liblrhsmm_rs_hsmm_path_log_probability_f64(retained,&likelihood) == 0); assert(isfinite(likelihood));
        assert(liblrhsmm_rs_hsmm_path_get_scores_f64(retained,&scores) == 0);
        assert(liblrhsmm_rs_hsmm_path_release_f64(&retained) == 0); read_scores_f64(scores, values);
        LiblrhsmmRsGeometricSettingsF64 geo;
        assert(liblrhsmm_rs_geometric_settings_default_f64(&geo) == 0); assert(geo.temperature == 1); geo.pruning_slope = 10;
        LiblrhsmmRsStateScoresF64 *geo_scores = NULL;
        assert(liblrhsmm_rs_model_forward_geometric_f64(model,seg,log,&geo,&geo_scores) == 0); assert(liblrhsmm_rs_state_scores_release_f64(&geo_scores) == 0);
        assert(liblrhsmm_rs_model_backward_geometric_f64(model,seg,log,&geo,&geo_scores) == 0); assert(liblrhsmm_rs_state_scores_release_f64(&geo_scores) == 0);
        LiblrhsmmRsGeometricPathF64 *geometric = NULL, *geo_clone = NULL;
        assert(liblrhsmm_rs_model_viterbi_geometric_f64(model,seg,log,&geo,&geometric) == 0);
        assert(liblrhsmm_rs_geometric_path_clone_f64(geometric,&geo_clone) == 0);
        assert(liblrhsmm_rs_geometric_path_release_f64(&geometric) == 0);
        LiblrhsmmRsHsmmScoresF64 *sentinel = (LiblrhsmmRsHsmmScoresF64 *)(uintptr_t)0x1000;
        options.temperature = NAN;
        assert(liblrhsmm_rs_model_forward_hsmm_f64(model,seg,log,&options,&sentinel) == 3); assert((uintptr_t)sentinel == 0x1000);
        assert(liblrhsmm_rs_model_release_f64(&model) == 0); assert(liblrhsmm_rs_segmentation_release_f64(&seg) == 0); assert(liblrhsmm_rs_transition_graph_release_f64(&graph) == 0); assert(liblrhsmm_rs_log_emissions_release_f64(&log) == 0);
        assert(liblrhsmm_rs_geometric_path_layout_f64(geo_clone,&layout) == 0); assert(layout.frames==12 && layout.states==4 && layout.occurrences==4);
        size_t states[12], ends[4];
        assert(liblrhsmm_rs_geometric_path_copy_states_f64(geo_clone,0,states,12) == 0);
        assert(liblrhsmm_rs_geometric_path_copy_boundaries_f64(geo_clone,0,ends,4) == 0);
        assert(states[0]==0 && states[11]==3 && ends[3]==12);
        for(size_t frame=1;frame<12;++frame) assert(states[frame]>=states[frame-1] && states[frame]<=states[frame-1]+1);
        assert(liblrhsmm_rs_geometric_path_log_probability_f64(geo_clone,&likelihood) == 0); assert(isfinite(likelihood));
        assert(liblrhsmm_rs_geometric_path_get_scores_f64(geo_clone,&geo_scores) == 0);
        assert(liblrhsmm_rs_geometric_path_release_f64(&geo_clone) == 0); assert(liblrhsmm_rs_state_scores_release_f64(&geo_scores) == 0);
        assert(liblrhsmm_rs_hsmm_path_release_f64(&path) == 0); assert(liblrhsmm_rs_geometric_path_release_f64(&geo_clone) == 0);
    }}
    assert(comparisons == 1536);
}

int main(void) { exercise_f32(); exercise_f64(); puts("Inference C: all70 exports, original C scores and occurrence paths passed"); return 0; }
